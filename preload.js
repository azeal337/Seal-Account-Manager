const { contextBridge, ipcRenderer } = require('electron');

window.addEventListener('DOMContentLoaded', async () => {
  const label = document.getElementById('appVersion');
  const footer = document.getElementById('appVersionFooter');
  if (!label && !footer) return;
  try {
    const version = await ipcRenderer.invoke('app:version');
    if (label) label.textContent = `v${version}`;
    if (footer) footer.textContent = `Seal Account Manager ${version}`;
  } catch (error) {
    console.warn('Could not read the SAM version:', error.message);
  }
}, { once: true });

