const assert = require('node:assert/strict');
const { createTarotDeck } = require('../src/tarotDeck');
const data = new Map();
const storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
let seed = 73;
const random = () => {
  seed = (Math.imul(1664525, seed) + 1013904223) >>> 0;
  return seed / 2 ** 32;
};
const name = (deck, key) => deck.cardsForSessions([key]).get(key).name;
const firstDeck = createTarotDeck(storage, random);
const firstBatch = [...firstDeck.cardsForSessions(['a', 'b', 'c']).values()].map(card => card.name);
assert.equal(new Set(firstBatch).size, 3);
assert.equal(name(firstDeck, 'a'), firstBatch[0]);
const resumed = createTarotDeck(storage, random);
assert.equal(name(resumed, 'a'), firstBatch[0]);
const firstCycle = [...firstBatch, ...Array.from({ length: 75 }, (_, index) => name(resumed, 'first-' + index))];
assert.equal(new Set(firstCycle).size, 78);
assert.equal(firstCycle.filter(value => value.endsWith(' of Wands')).length, 14);
assert.equal(firstCycle.filter(value => value.endsWith(' of Cups')).length, 14);
assert.equal(firstCycle.filter(value => value.endsWith(' of Swords')).length, 14);
assert.equal(firstCycle.filter(value => value.endsWith(' of Pentacles')).length, 14);
assert.equal(name(resumed, 'b'), firstBatch[1], 'refresh does not start the next cycle');
const secondCycle = Array.from({ length: 78 }, (_, index) => name(resumed, 'second-' + index));
assert.deepEqual(new Set(secondCycle), new Set(firstCycle));
assert.notDeepEqual(secondCycle, firstCycle, 'reshuffling changes the draw order');
assert.equal(name(resumed, 'a'), firstBatch[0], 'new cycles leave existing rows alone');
for (let index = 0; index < 300; index++) resumed.cardsForSessions(['a', 'recent-' + index]);
assert.equal(name(resumed, 'a'), firstBatch[0], 'active rows survive history trimming');
console.log('PASS: 78 unique cards per cycle, persisted order, stable session draws, reshuffle and bounded history.');
